// Generates src/api/openapi.gen.ts (TypeScript types only) from the API's OpenAPI document (spec 020).
// Source: the sibling repo's ../atlas-api/openapi.generated.json, or the deployed /openapi.json when that file is absent.
// Usage: npm run api:types            -> write the file (commit it; src/api/contract-check.ts makes `tsc` fail on zod drift)
//        npm run api:types -- --check -> exit 1 if the committed file is stale
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS from 'openapi-typescript';

const local = fileURLToPath(new URL('../../atlas-api/openapi.generated.json', import.meta.url));
const remote = 'https://atlas-api.fastapicloud.dev/openapi.json';
const out = fileURLToPath(new URL('../src/api/openapi.gen.ts', import.meta.url));

const useLocal = existsSync(local);
const doc = useLocal ? JSON.parse(readFileSync(local, 'utf8')) : await fetch(remote).then((r) => r.json());
const ts = `// GENERATED by \`npm run api:types\` from the Atlas API OpenAPI document. Do not edit.\n${await openapiTS(doc, { alphabetize: true })}`;
const source = useLocal ? 'atlas-api/openapi.generated.json' : remote;

if (process.argv.includes('--check')) {
  const same = existsSync(out) && readFileSync(out, 'utf8') === ts;
  console.log(same ? `up to date with ${source}` : `STALE: run npm run api:types (source: ${source})`);
  process.exit(same ? 0 : 1);
}
writeFileSync(out, ts);
console.log(`wrote src/api/openapi.gen.ts from ${source}`);
