// Spec 021 item 7: coarse land mask (2.5 degree cells, 144 x 72) for the loading screen's dot matrix, written to src/lib/landmask.ts.
// It must exist before any map file has arrived, so it is baked in (~2.6 kB). Usage: npm run landmask
import { readFileSync, writeFileSync } from 'node:fs';
import { geoBounds, geoContains } from 'd3-geo';
import type { Feature } from 'geojson';

const STEP = 2.5;
const COLS = 360 / STEP;
const ROWS = 180 / STEP;
const geo = JSON.parse(readFileSync('public/data/modern.geojson', 'utf8')) as { features: Feature[] };
const items = geo.features.filter((f) => f.properties?.NAME !== 'Antarctica').map((f) => ({ f, b: geoBounds(f) }));
const rows: string[] = [];
for (let r = 0; r < ROWS; r++) {
  const lat = 90 - STEP * (r + 0.5);
  let bits = '';
  for (let c = 0; c < COLS; c++) {
    const lng = -180 + STEP * (c + 0.5);
    const hit = items.some(({ f, b: [[w, s], [e, n]] }) => (w! <= e! ? lng >= w! && lng <= e! : lng >= w! || lng <= e!) && lat >= s! && lat <= n! && geoContains(f, [lng, lat]));
    bits += hit ? '1' : '0';
  }
  rows.push(bits.match(/.{1,4}/g)!.map((n) => parseInt(n, 2).toString(16)).join(''));
}
writeFileSync('src/lib/landmask.ts', `// GENERATED by scripts/landmask.ts (npm run landmask) from public/data/modern.geojson. Do not edit by hand.
// Land (1) / sea (0) per ${STEP} degree cell, north to south, west to east; each row is ${COLS} bits as hex. Antarctica is left out.
export const LAND_STEP = ${STEP};
export const LAND_COLS = ${COLS};
export const LAND_ROWS: readonly string[] = [
${rows.map((r) => `  '${r}',`).join('\n')}
];
`);
console.log('wrote src/lib/landmask.ts');
