const slugify = (s: string) =>
  s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/&/g, 'and').replace(/['.]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const geo = JSON.parse(readFileSync('public/data/modern.geojson', 'utf8')) as { features: { properties: { ISO2?: string; NAME: string } }[] };
const countries = geo.features.flatMap((f) => (f.properties.ISO2 ? [{ iso2: f.properties.ISO2, name: f.properties.NAME }] : []));

const browser = await chromium.launch();
const found: Record<string, string> = {};
type Country = (typeof countries)[number];

async function check(page: import('playwright').Page, slug: string, timeout: number) {
  await page.goto(`https://www.plonkit.net/${slug}`, { waitUntil: 'networkidle' });
  // The SPA sets the title after load; an unknown slug keeps "Plonk It", so a timeout means "no guide".
  return page
    .waitForFunction(() => document.title.endsWith(' — Plonk It'), undefined, { timeout })
    .then(() => true, () => false);
}

/** Checks every country; returns the ones without a confirmed guide. */
async function scan(list: Country[], workers: number, timeout: number): Promise<Country[]> {
  const queue = [...list];
  const misses: Country[] = [];
  await Promise.all(Array.from({ length: workers }, async () => {
    const page = await browser.newPage();
    for (let c = queue.shift(); c; c = queue.shift()) {
      let hit: string | undefined;
      for (const slug of ALIASES[c.name] ?? [slugify(c.name)]) if (await check(page, slug, timeout)) { hit = slug; break; }
      if (hit) found[c.iso2] = hit; else misses.push(c);
    }
    await page.close();
  }));
  return misses;
}

// The site is slow under parallel load and a slow page looks like "no guide": retry misses one at a time, longer.
const missing = (await scan(await scan(countries, 2, 8000), 1, 20000)).map((c) => `${c.iso2} ${c.name}`);
await browser.close();

const entries = Object.entries(found).sort(([a], [b]) => a.localeCompare(b));
writeFileSync('src/lib/plonkit.ts', `// GENERATED by scripts/plonkit-slugs.ts (npm run plonkit) on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// ISO2 -> plonkit.net guide slug. Absent = no guide found. We link to Plonk It; their guide content is theirs and is never copied.
export const PLONKIT_SLUGS: Readonly<Record<string, string>> = {
${entries.map(([k, v]) => `  ${k}: '${v}',`).join('\n')}
};

export const plonkitUrl = (iso2: string): string | null => {
  const slug = PLONKIT_SLUGS[iso2];
  return slug ? \`https://www.plonkit.net/\${slug}\` : null;
};
`);
console.log(`${entries.length} guides found, ${missing.length} without:\n${missing.sort().join('\n')}`);
