// Spec 021 item 6: which countries have official Google Street View coverage, from Wikipedia's "Google Street View coverage"
// table (CC BY-SA 4.0), fetched through the MediaWiki API. Writes src/lib/streetview.ts (iso2 -> level); we store only a
// classification, never the page text. Names are mapped to ISO2 via public/data/modern.geojson NAME, i18n-iso-countries and a
// small alias table; names that map to nothing are printed.
// Usage: npm run streetview
import { readFileSync, writeFileSync } from 'node:fs';
import countries from 'i18n-iso-countries';
import en from 'i18n-iso-countries/langs/en.json' with { type: 'json' };
import { parseCoverage, type Coverage } from './streetview-parse';

countries.registerLocale(en);
const PAGE = 'Google_Street_View_coverage';
const res = await fetch(`https://en.wikipedia.org/w/api.php?action=parse&page=${PAGE}&prop=wikitext%7Crevid&format=json&formatversion=2`, {
  headers: { 'User-Agent': 'atlas-geo-build/1.0 (coverage classification script)' },
});
if (!res.ok) throw new Error(`MediaWiki API: HTTP ${res.status}`);
const { parse } = (await res.json()) as { parse: { wikitext: string; revid: number } };
const rows = parseCoverage(parse.wikitext);

// page name -> ISO2, where neither Natural Earth nor i18n-iso-countries matches
const ALIASES: Record<string, string> = {
  'Åland Islands': 'AX', 'Bosnia and Herzegovina': 'BA', 'Cape Verde': 'CV', 'Czech Republic': 'CZ', 'Czechia': 'CZ',
  'Democratic Republic of the Congo': 'CD', 'Republic of the Congo': 'CG', 'East Timor': 'TL', 'Eswatini': 'SZ', 'Swaziland': 'SZ',
  'Faroe Islands': 'FO', 'The Gambia': 'GM', 'Gambia': 'GM', 'Hong Kong': 'HK', 'Macau': 'MO', 'Ivory Coast': 'CI',
  'North Macedonia': 'MK', 'Palestine': 'PS', 'Russia': 'RU', 'South Korea': 'KR', 'Turkey': 'TR', 'Türkiye': 'TR',
  'United States': 'US', 'United Kingdom': 'GB', 'Vatican City': 'VA', 'Micronesia': 'FM', 'Myanmar': 'MM', 'Taiwan': 'TW',
  'Curaçao': 'CW', 'São Tomé and Príncipe': 'ST', 'United States Virgin Islands': 'VI', 'Akrotiri and Dhekelia': 'XX', 'Saint Martin': 'MF', 'Sint Maarten': 'SX', 'Saint Barthélemy': 'BL', 'Svalbard and Jan Mayen': 'SJ',
  'South Georgia and the South Sandwich Islands': 'GS', 'Falkland Islands': 'FK', 'Réunion': 'RE', 'Pitcairn Islands': 'PN',
};
const geo = JSON.parse(readFileSync('public/data/modern.geojson', 'utf8')) as { features: { properties: { ISO2?: string; NAME: string } }[] };
const byName = new Map(geo.features.flatMap((f) => (f.properties.ISO2 ? [[f.properties.NAME.toLowerCase(), f.properties.ISO2] as const] : [])));
const polygonIds = new Set(geo.features.flatMap((f) => (f.properties.ISO2 ? [f.properties.ISO2] : [])));

const rank: Record<Coverage, number> = { full: 2, partial: 1, limited: 0 };
const found: Record<string, Coverage> = {};
const unmapped: string[] = [];
const noPolygon: string[] = [];
for (const [name, level] of rows) {
  const iso = ALIASES[name] ?? byName.get(name.toLowerCase()) ?? countries.getAlpha2Code(name, 'en');
  if (!iso) unmapped.push(name);
  else if (!polygonIds.has(iso)) noPolygon.push(`${name} (${iso})`);
  else if (!found[iso] || rank[level] > rank[found[iso]]) found[iso] = level;
}

const entries = Object.entries(found).sort(([a], [b]) => a.localeCompare(b));
const count = (l: Coverage) => entries.filter(([, v]) => v === l).length;
const date = new Date().toISOString().slice(0, 10);
writeFileSync('src/lib/streetview.ts', `// GENERATED by scripts/streetview-coverage.ts (npm run streetview). Do not edit by hand.
// Source: Wikipedia, "Google Street View coverage", section "Current coverage"
//   https://en.wikipedia.org/wiki/${PAGE} (revision ${parse.revid}, retrieved ${date}), licence CC BY-SA 4.0
//   https://creativecommons.org/licenses/by-sa/4.0/ . Only a classification per country is stored, derived from the table's markup.
export type Coverage = 'full' | 'partial' | 'limited';
export const STREETVIEW_SOURCE = {
  title: 'Wikipedia: Google Street View coverage',
  url: 'https://en.wikipedia.org/wiki/${PAGE}',
  license: 'CC BY-SA 4.0',
  retrieved: '${date}',
} as const;
/** full = public Street View (bold + asterisk on the page); partial = official but restricted (bold, no asterisk); limited = only businesses/attractions (plain text). Absent = none. */
export const STREETVIEW: Readonly<Record<string, Coverage>> = {
${entries.map(([k, v]) => `  ${k}: '${v}',`).join('\n')}
};
`);
console.log(`rows ${rows.length}; mapped ${entries.length} (full ${count('full')}, partial ${count('partial')}, limited ${count('limited')})`);
console.log('unmapped names:', unmapped.length ? unmapped.join('; ') : 'none');
console.log('mapped but no polygon in modern.geojson:', noPolygon.length ? noPolygon.join('; ') : 'none');
